package com.orchestrivo.util;

import com.orchestrivo.domain.ProcessSpec;
import com.orchestrivo.model.WorkloadRecord;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

class ReproducibilitySeedTest {

    @Test
    @DisplayName("Identical seed and configuration produces strictly identical process specifications")
    void testIdenticalSeedReproducibility() {
        long seed = 1234567890L;
        WorkloadGenerator.GeneratorConfig config1 = new WorkloadGenerator.GeneratorConfig(
                "Batch A", 25, 0, 50, 1, 20, seed
        );
        WorkloadGenerator.GeneratorConfig config2 = new WorkloadGenerator.GeneratorConfig(
                "Batch B", 25, 0, 50, 1, 20, seed
        );

        List<ProcessSpec> procs1 = WorkloadGenerator.generateProcesses(config1);
        List<ProcessSpec> procs2 = WorkloadGenerator.generateProcesses(config2);

        assertEquals(procs1.size(), procs2.size());
        assertEquals(procs1, procs2, "Generated processes with identical seed must match exactly");
    }

    @Test
    @DisplayName("Differing seeds produce different process distributions")
    void testDifferingSeedsProduceDifferentProcesses() {
        WorkloadGenerator.GeneratorConfig config1 = new WorkloadGenerator.GeneratorConfig(
                "Batch A", 25, 0, 50, 1, 20, 11111L
        );
        WorkloadGenerator.GeneratorConfig config2 = new WorkloadGenerator.GeneratorConfig(
                "Batch B", 25, 0, 50, 1, 20, 99999L
        );

        List<ProcessSpec> procs1 = WorkloadGenerator.generateProcesses(config1);
        List<ProcessSpec> procs2 = WorkloadGenerator.generateProcesses(config2);

        assertNotEquals(procs1, procs2, "Workloads generated from differing seeds must diverge");
    }

    @Test
    @DisplayName("Auto-generated cryptographic seed is non-negative and positive")
    void testAutoGeneratedSeedValidity() {
        long seed1 = WorkloadGenerator.generateSecureSeed();
        long seed2 = WorkloadGenerator.generateSecureSeed();

        assertTrue(seed1 > 0, "Generated seed must be positive");
        assertTrue(seed2 > 0, "Generated seed must be positive");
        assertNotEquals(seed1, seed2, "Consecutive auto-generated seeds must be distinct");

        WorkloadGenerator.GeneratorConfig defaultCfg = new WorkloadGenerator.GeneratorConfig();
        assertTrue(defaultCfg.getSeed() > 0, "Default config seed must be initialized to a positive number");

        defaultCfg.setName("Auto Workload");
        defaultCfg.setProcessCount(10);
        defaultCfg.setMinArrival(0);
        defaultCfg.setMaxArrival(10);
        defaultCfg.setMinBurst(1);
        defaultCfg.setMaxBurst(10);

        WorkloadRecord record = WorkloadGenerator.generateWorkloadRecord(10L, defaultCfg);
        assertNotNull(record.getGenerationSeed());
        assertTrue(record.getGenerationSeed() > 0);
    }
}
